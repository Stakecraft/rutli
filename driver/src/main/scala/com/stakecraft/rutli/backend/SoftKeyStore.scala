package com.stakecraft.rutli.backend

import org.bouncycastle.crypto.digests.SHA256Digest
import org.bouncycastle.crypto.generators.HKDFBytesGenerator
import org.bouncycastle.crypto.params.HKDFParameters

import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Path, StandardOpenOption}
import java.security.SecureRandom
import javax.crypto.Cipher
import javax.crypto.spec.{GCMParameterSpec, SecretKeySpec}
import scala.jdk.CollectionConverters._
import scala.util.Using

/** Sealed at-rest persistence for [[SoftwareBackend]] keys.
  *
  * Every record is one file `<keyId>.sealed`: a small versioned envelope of
  * `magic ‖ 12-byte nonce ‖ AES-256-GCM(payload)`, keyed via HKDF-SHA256 from an operator-injected
  * master secret (mirroring the cosigner's share sealing — the secret comes from the environment,
  * never from disk). Payload is a JSON object serialized by the backend (key kind, spec, PKCS#8 /
  * X.509 / raw key bytes, base64).
  *
  * Writes are atomic (temp file + move) and fsynced (file, then directory) — a half-written key
  * file after a crash must never exist, because a lost encryption key is unrecoverable.
  */
final class SoftKeyStore(dir: Path, masterSecret: Array[Byte]) {

  import SoftKeyStore._

  Files.createDirectories(dir)

  private val sealKey: SecretKeySpec = {
    val hkdf = new HKDFBytesGenerator(new SHA256Digest())
    hkdf.init(new HKDFParameters(masterSecret, Salt, Info))
    val out = new Array[Byte](32)
    hkdf.generateBytes(out, 0, 32)
    new SecretKeySpec(out, "AES")
  }

  /** Persist `payload` (plaintext JSON bytes) for `keyId`, sealed. Atomic + durable. */
  def put(keyId: String, payload: Array[Byte]): Unit = {
    val nonce = new Array[Byte](NonceLen)
    random.nextBytes(nonce)
    val cipher = Cipher.getInstance("AES/GCM/NoPadding")
    cipher.init(Cipher.ENCRYPT_MODE, sealKey, new GCMParameterSpec(TagBits, nonce))
    // Bind the ciphertext to its key id — a sealed file cannot be renamed onto another id.
    cipher.updateAAD(keyId.getBytes(StandardCharsets.UTF_8))
    val envelope = Magic ++ nonce ++ cipher.doFinal(payload)

    val target = fileFor(keyId)
    val tmp = target.resolveSibling(target.getFileName.toString + ".tmp")
    Files.write(tmp, envelope, StandardOpenOption.CREATE, StandardOpenOption.TRUNCATE_EXISTING)
    fsync(tmp)
    Files.move(tmp, target, java.nio.file.StandardCopyOption.ATOMIC_MOVE, java.nio.file.StandardCopyOption.REPLACE_EXISTING)
    fsyncDir(dir)
  }

  /** Load and unseal every persisted key: (keyId, plaintext payload). Fails loudly on a wrong
    * secret or tampered file — silently skipping an unreadable private key would be worse.
    */
  def loadAll(): Seq[(String, Array[Byte])] =
    Using.resource(Files.list(dir)) { stream =>
      stream.iterator().asScala.toSeq
        .filter(p => p.getFileName.toString.endsWith(Suffix))
        .sortBy(_.getFileName.toString)
        .map { p =>
          val keyId = p.getFileName.toString.stripSuffix(Suffix)
          val bytes = Files.readAllBytes(p)
          require(
            bytes.length > Magic.length + NonceLen && bytes.startsWith(Magic),
            s"not a rutli sealed key file: $p",
          )
          val nonce = bytes.slice(Magic.length, Magic.length + NonceLen)
          val ct = bytes.drop(Magic.length + NonceLen)
          val cipher = Cipher.getInstance("AES/GCM/NoPadding")
          cipher.init(Cipher.DECRYPT_MODE, sealKey, new GCMParameterSpec(TagBits, nonce))
          cipher.updateAAD(keyId.getBytes(StandardCharsets.UTF_8))
          keyId -> cipher.doFinal(ct) // AEADBadTagException on wrong secret / tamper
        }
    }

  def delete(keyId: String): Unit = {
    Files.deleteIfExists(fileFor(keyId))
    fsyncDir(dir)
  }

  private def fileFor(keyId: String): Path = {
    // Key ids are generated by the backend from [A-Za-z0-9_.-] only; refuse anything else rather
    // than risk path tricks on ids that arrived from disk or config.
    require(keyId.matches("[A-Za-z0-9_.-]+"), s"unsafe key id for filename: $keyId")
    dir.resolve(keyId + Suffix)
  }
}

object SoftKeyStore {
  private val Magic = "RUTLISOFT1".getBytes(StandardCharsets.UTF_8)
  private val Salt = "rutli-softbackend-seal-v1".getBytes(StandardCharsets.UTF_8)
  private val Info = "aes-256-gcm".getBytes(StandardCharsets.UTF_8)
  private val Suffix = ".sealed"
  private val NonceLen = 12
  private val TagBits = 128
  private val random = new SecureRandom()

  private def fsync(p: Path): Unit =
    Using.resource(java.nio.channels.FileChannel.open(p, StandardOpenOption.READ))(_.force(true))

  private def fsyncDir(dir: Path): Unit =
    // Directory fsync is best-effort on non-POSIX filesystems.
    try Using.resource(java.nio.channels.FileChannel.open(dir, StandardOpenOption.READ))(_.force(true))
    catch { case _: Exception => () }
}
