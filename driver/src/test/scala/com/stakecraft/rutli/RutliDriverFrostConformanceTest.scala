package com.stakecraft.rutli

import com.digitalasset.canton.crypto.kms.driver.api.v1.{EncryptionKeySpec, KmsDriver, SigningKeySpec}
import com.digitalasset.canton.crypto.kms.driver.testing.v1.KmsDriverTest
import com.stakecraft.rutli.policy.ApprovalGate

import scala.concurrent.duration._
import scala.concurrent.{Await, Future}

/** The upstream Canton driver conformance suite against [[RutliDriver]] over the **frost backend
  * with cluster-hosted keys and no delegate** — the production shape of `deploy/devnet/
  * canton-hosted.conf` — talking to [[CryptoFakeCluster]], an in-process cosigner that does the
  * cryptography for real on the JDK's providers.
  *
  * Because the cluster reports `ec-p256-ecies`, the driver advertises `EcP256` /
  * `EciesHkdfHmacSha256Aes128Cbc`, and the suite encrypts with Canton's own `JcePureCrypto` and
  * decrypts through `decryptAsymmetric`: a JVM-encrypt → driver-decrypt differential for Canton's
  * ECIES framing (and RSA-OAEP, Ed25519 signing, the symmetric key) — what docs/hosted-keys-design.md
  * asked for before ECIES could be advertised.
  *
  * Keys are predefined (minted through the backend before the suite) rather than generated by it:
  * the suite deletes every key it generates, and the driver deliberately refuses to delete a FROST
  * key (the namespace key is not rotatable). Generation of every advertised spec is covered by
  * FrostEciesSpec and FrostHostedKeysSpec.
  *
  * Runs only with `CONFORMANCE=1` (build.sbt), like the software-backend suite.
  */
class RutliDriverFrostConformanceTest extends KmsDriverTest {

  private lazy val running =
    CryptoFakeCluster.start(new CryptoFakeCluster, simpleLoggerFactory(classOf[RutliDriverFrostConformanceTest]))(
      parallelExecutionContext
    )

  private lazy val minted: (String, String, String, String) = {
    implicit val ec: scala.concurrent.ExecutionContext = parallelExecutionContext
    val b = running.backend
    Await.result(
      for {
        ed <- b.generateSigningKeyPair(SigningKeySpec.EcCurve25519, Some("conformance-signing"))
        ecies <- b.generateEncryptionKeyPair(EncryptionKeySpec.EcP256, Some("conformance-ecies"))
        rsa <- b.generateEncryptionKeyPair(EncryptionKeySpec.Rsa2048, Some("conformance-rsa"))
        sym <- b.generateSymmetricKey(Some("conformance-sym"))
      } yield (ed, ecies, rsa, sym),
      60.seconds,
    )
  }

  override protected val predefinedSigningKeys: Map[SigningKeySpec, String] =
    Map(SigningKeySpec.EcCurve25519 -> minted._1)
  override protected val predefinedEncryptionKeys: Map[EncryptionKeySpec, String] =
    Map(EncryptionKeySpec.EcP256 -> minted._2, EncryptionKeySpec.Rsa2048 -> minted._3)
  override protected val predefinedSymmetricKey: Option[String] = Some(minted._4)

  override def afterAll(): Unit =
    try super.afterAll()
    finally running.close()

  override protected def newKmsDriver(): KmsDriver = {
    val backend = running.backend
    new RutliDriver(
      backend,
      simpleLoggerFactory(classOf[RutliDriver]),
      auditLogging = false,
      auditLog = None,
      new ApprovalGate {
        override def authorize(keyId: String, data: Array[Byte]): Future[Unit] = Future.unit
      },
      signingJournal = None,
      backend.supportedSigningKeySpecs,
      backend.supportedSigningAlgoSpecs,
      backend.supportedEncryptionKeySpecs,
      backend.supportedEncryptionAlgoSpecs,
    )(parallelExecutionContext)
  }

  "MPC KMS Driver (frost backend, cluster-hosted keys, ECIES)" must {
    // The advertised set this suite exercises, so a regression that stops advertising ECIES fails
    // here rather than silently testing less.
    "advertise ECIES over P-256" in {
      val d = newKmsDriver()
      d.supportedEncryptionKeySpecs should contain(EncryptionKeySpec.EcP256)
      d.supportedEncryptionAlgoSpecs should contain(
        com.digitalasset.canton.crypto.kms.driver.api.v1.EncryptionAlgoSpec.EciesHkdfHmacSha256Aes128Cbc
      )
    }
    behave like kmsDriver(allowKeyGeneration = false)
  }
}
