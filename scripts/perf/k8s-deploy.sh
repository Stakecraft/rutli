# Install Rütli into one namespace of an existing Kubernetes cluster for the cluster suite
# (scripts/perf/run.py --env k8s): a throwaway CA, certificates and seal bundles, the chart
# deploy/helm/rutli-cosigner with three cosigners, and a load generator pod. The cluster is
# whatever KUBECONFIG points at; this script creates nothing outside the namespace.
#
# Usage:
#   scripts/perf/k8s-deploy.sh install   --image REF --work DIR [options]
#   scripts/perf/k8s-deploy.sh upgrade   --image REF --work DIR [--namespace NS]
#   scripts/perf/k8s-deploy.sh uninstall [--namespace NS]
#
#   install    The namespace (created unless it exists), the secrets, the load generator and its
#              NetworkPolicy (scripts/perf/k8s/loadgen.yaml), and the chart.
#   upgrade    helm upgrade the cosigners to --image, with the values of the install.
#   uninstall  Everything install made: the release, the cosigners' volumes (the chart keeps them
#              on uninstall), the secrets and the pod; the namespace too if install created it.
#
# Options:
#   --namespace NS          default rutli-perf. An existing namespace must not hold a release
#                           named rutli-cosigner.
#   --image REF             the image of frost/Dockerfile.perf (cosigner + load generator), pullable
#                           by the cluster. The load generator always runs it; the cosigners too
#                           unless --previous.
#   --previous              the cosigners start on --previous-image (default: the chart's default,
#                           the previous release), so that `upgrade` then moves live keys.
#   --previous-image REF    the previous release's image, e.g. from a registry the cluster may use.
#   --work DIR              certificates, seal bundles and values (secrets of the throwaway cluster).
#   --storage-class NAME    for the cosigners' volumes (default: the cluster's default class).
#   --pull-secret NAME      an existing image pull secret in the namespace, for both images.
#   --values FILE           more chart values (resources, tolerations, node selection, ...); may
#                           be repeated. Applied after this script's, on install and upgrade.
#
# The cosigners keep the chart's defaults (NetworkPolicy on, Pod Security "restricted", read-only
# root file system) with these exceptions: hosted keys on; ReadWriteOnce volumes (ReadWriteOncePod
# needs a CSI driver); the sign rate limit lifted except for keys named perf-limited*, as in
# scripts/perf-load.sh.
#
# Requires: kubectl, helm, openssl. No Docker: the seal bundles are generated by the image itself,
# inside the load generator pod.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
CHART="$REPO/deploy/helm/rutli-cosigner"
MANIFEST="$REPO/scripts/perf/k8s/loadgen.yaml"
RELEASE=rutli-cosigner

cmd="${1:-}"
shift || true
ns=rutli-perf image="" work="" previous=0 previous_image="" storage_class="" pull_secret=""
extra_values=()
while [ $# -gt 0 ]; do
  case "$1" in
    --namespace | --image | --work | --storage-class | --previous-image | --pull-secret | --values)
      [ $# -ge 2 ] || { echo "ERROR: $1 needs a value" >&2; exit 2; }
      case "$1" in
        --namespace) ns="$2" ;;
        --image) image="$2" ;;
        --work) work="$2" ;;
        --storage-class) storage_class="$2" ;;
        --previous-image) previous_image="$2" ;;
        --pull-secret) pull_secret="$2" ;;
        --values) extra_values+=(-f "$(cd "$(dirname "$2")" && pwd)/$(basename "$2")") ;;
      esac
      shift 2 ;;
    --previous) previous=1; shift ;;
    *) echo "ERROR: unknown argument $1" >&2; exit 2 ;;
  esac
done
case "$cmd" in install | upgrade | uninstall) ;; *) sed -n '5,41p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 2 ;; esac
[[ "$ns" =~ ^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$ ]] || { echo "ERROR: --namespace is not a valid namespace name" >&2; exit 2; }
k() { kubectl -n "$ns" "$@"; }

wait_cosigners() {
  for i in 1 2 3; do
    k rollout status "statefulset/$RELEASE-n$i" --timeout=600s
  done
}

split_image() { # REF -> "repository tag" (a tag may carry @sha256:...)
  local ref="$1" repo tag
  case "$ref" in
    *@*)
      # The chart renders repository:tag, so a digest needs a tag in front of it.
      repo="${ref%%@*}"; tag="${ref#*@}"
      case "${repo##*/}" in
        *:*) tag="${repo##*:}@$tag"; repo="${repo%:*}" ;;
        *) echo "ERROR: image $ref: give a tag before the digest (name:tag@sha256:...)" >&2; exit 2 ;;
      esac ;;
    *)
      case "${ref##*/}" in
        *:*) repo="${ref%:*}"; tag="${ref##*:}" ;;
        *) echo "ERROR: image $ref has no tag" >&2; exit 2 ;;
      esac ;;
  esac
  echo "$repo $tag"
}

image_args() { # REF -> --set-string flags for the chart
  local parts
  read -r -a parts <<<"$(split_image "$1")"
  echo "--set-string image.repository=${parts[0]} --set-string image.tag=${parts[1]} --set image.pullPolicy=IfNotPresent"
}

annotation() { kubectl get namespace "$ns" -o "jsonpath={.metadata.annotations.rutli-perf/$1}" 2>/dev/null || true; }

if [ "$cmd" = uninstall ]; then
  # Only what an install of this script made: a namespace it did not install into is refused, and
  # inside it only objects carrying its label are deleted.
  if [ "$(annotation installed)" != "true" ]; then
    echo "ERROR: namespace $ns was not installed by this script (no rutli-perf/installed annotation): refusing" >&2
    exit 1
  fi
  echo "==> Uninstalling from namespace $ns"
  helm uninstall "$RELEASE" -n "$ns" --wait 2>/dev/null || true
  # The chart keeps its volumes on uninstall; these are the ones the install labelled.
  k delete pvc -l rutli-perf/suite=1 --ignore-not-found --wait=false
  k delete pod,secret,networkpolicy -l rutli-perf/suite=1 --ignore-not-found
  if [ "$(annotation created-by-suite)" = "true" ]; then
    kubectl delete namespace "$ns" --wait=false
  else
    kubectl annotate namespace "$ns" rutli-perf/installed- >/dev/null
  fi
  exit 0
fi

[ -n "$image" ] && [ -n "$work" ] || { echo "ERROR: --image and --work are required" >&2; exit 2; }
split_image "$image" >/dev/null
[ -z "$previous_image" ] || split_image "$previous_image" >/dev/null
mkdir -p "$work"
work="$(cd "$work" && pwd)"

if [ "$cmd" = upgrade ]; then
  echo "==> helm upgrade to $image"
  # shellcheck disable=SC2046 # image_args prints flags meant to be split
  helm upgrade "$RELEASE" "$CHART" -n "$ns" -f "$work/values.yaml" ${extra_values[@]+"${extra_values[@]}"} $(image_args "$image")
  wait_cosigners
  exit 0
fi

# -- install ------------------------------------------------------------------------------------

if kubectl get namespace "$ns" >/dev/null 2>&1; then
  if helm status "$RELEASE" -n "$ns" >/dev/null 2>&1; then
    echo "ERROR: namespace $ns already holds a release $RELEASE" >&2
    exit 1
  fi
  echo "==> Using the existing namespace $ns"
else
  kubectl create namespace "$ns"
  kubectl annotate namespace "$ns" rutli-perf/created-by-suite=true
fi
# What `uninstall` checks before it deletes anything.
kubectl annotate namespace "$ns" --overwrite rutli-perf/installed=true
# What the chart's NetworkPolicy admits clients by, and the Pod Security level its pods meet. On a
# cluster where this script may not label namespaces, the owner of the namespace sets both.
kubectl label namespace "$ns" --overwrite rutli.io/client-ns=true pod-security.kubernetes.io/enforce=restricted \
  || echo "WARNING: could not label namespace $ns; it needs rutli.io/client-ns=true for the load generator to reach the cosigners" >&2

echo "==> Certificates (throwaway CA)"
"$REPO/scripts/gen-frost-certs.sh" 3 "$work/certs"
label() { k label "$@" rutli-perf/suite=1 --overwrite >/dev/null; }
k create secret generic rutli-cosigner-ca --from-file=ca.crt="$work/certs/ca.crt"
label secret rutli-cosigner-ca
for i in 1 2 3; do
  k create secret tls "rutli-cosigner-tls-$i" --cert="$work/certs/cosigner$i.crt" --key="$work/certs/cosigner$i.key"
  label secret "rutli-cosigner-tls-$i"
done
k create secret generic rutli-perf-driver --from-file=ca.crt="$work/certs/ca.crt" \
  --from-file=driver.crt="$work/certs/driver.crt" --from-file=driver.key="$work/certs/driver.key"
k create secret generic rutli-perf-peer --from-file=peer.crt="$work/certs/cosigner1.crt" \
  --from-file=peer.key="$work/certs/cosigner1.key"
label secret rutli-perf-driver
label secret rutli-perf-peer

echo "==> Load generator pod and its NetworkPolicy"
pull_secrets="[]"
[ -z "$pull_secret" ] || pull_secrets="[{ name: \"$pull_secret\" }]"
node_selector="{}"
if kubectl get nodes -l rutli-perf/role=loadgen -o name 2>/dev/null | grep -q .; then
  node_selector='{ "rutli-perf/role": loadgen }'
fi
sed -e "s|__IMAGE__|$image|" -e "s|__PULL_SECRETS__|$pull_secrets|" -e "s|__NODE_SELECTOR__|$node_selector|" "$MANIFEST" \
  | k apply -f -
k wait --for=condition=Ready pod/rutli-perf-loadgen --timeout=300s

# The image the cosigners start on: the build under test, or the previous release.
cosigner_image="$image"
if [ "$previous" -eq 1 ]; then
  cosigner_image="$previous_image"
  if [ -z "$cosigner_image" ]; then
    # The chart's default image.
    cosigner_image="$(awk '/^image:/ {on=1; next} on && /^[^ ]/ {on=0} on && $1 == "repository:" {r=$2} on && $1 == "tag:" {gsub(/"/, "", $2); t=$2} END {print r ":" t}' "$CHART/values.yaml")"
  fi
  echo "    the cosigners start on $cosigner_image (the previous release)"
fi

# The seal bundles are generated by the image that will first read them, in a pod of its own
# (no network use, nothing mounted but an in-memory /tmp), so that a bundle format of the build
# under test never meets the previous release.
echo "==> Seal bundles (generated inside the cluster by $cosigner_image)"
k apply -f - <<YAML
apiVersion: v1
kind: Pod
metadata:
  name: rutli-perf-seal
  labels: { rutli-perf/suite: "1", app.kubernetes.io/name: rutli-perf-seal }
spec:
  automountServiceAccountToken: false
  enableServiceLinks: false
  restartPolicy: Never
  imagePullSecrets: $pull_secrets
  securityContext: { runAsNonRoot: true, runAsUser: 10001, runAsGroup: 10001, seccompProfile: { type: RuntimeDefault } }
  containers:
    - name: seal
      image: $cosigner_image
      imagePullPolicy: IfNotPresent
      command: ["sleep", "3600"]
      securityContext: { allowPrivilegeEscalation: false, readOnlyRootFilesystem: true, capabilities: { drop: ["ALL"] } }
      volumeMounts: [{ name: tmp, mountPath: /tmp }]
  volumes: [{ name: tmp, emptyDir: { medium: Memory, sizeLimit: 1Mi } }]
YAML
k wait --for=condition=Ready pod/rutli-perf-seal --timeout=300s
(umask 077 && mkdir -p "$work/seal")
dist=()
for i in 1 2 3; do
  out="$(k exec rutli-perf-seal -- rutli-cosigner seal new-node --node "$i" --out "/tmp/node-$i.json")"
  key="$(printf '%s\n' "$out" | awk '/dist_public_key =/ {print $3}')"
  [[ "$key" =~ ^[0-9a-f]{64}$ ]] || { echo "ERROR: seal new-node printed no dist_public_key for node $i" >&2; exit 1; }
  (umask 077 && k exec rutli-perf-seal -- cat "/tmp/node-$i.json" >"$work/seal/node-$i.json")
  k create secret generic "rutli-seal-node-$i" --from-file=node.json="$work/seal/node-$i.json"
  label secret "rutli-seal-node-$i"
  dist+=("$key")
done
k delete pod rutli-perf-seal --wait=false

selector="{}"
if kubectl get nodes -l rutli-perf/role=cosigner -o name 2>/dev/null | grep -q .; then
  selector='{ "rutli-perf/role": cosigner }'
fi
pull_values="[]"
[ -z "$pull_secret" ] || pull_values="[{ name: \"$pull_secret\" }]"
cat >"$work/values.yaml" <<EOF
replicaCount: 3
threshold: 2
nodes:
  - { id: 1, distPublicKey: "${dist[0]}" }
  - { id: 2, distPublicKey: "${dist[1]}" }
  - { id: 3, distPublicKey: "${dist[2]}" }
hostedKeys:
  enabled: true
  commitmentKey: "$(openssl rand -hex 32)"
persistence:
  accessModes: [ReadWriteOnce]
  storageClassName: "$storage_class"
imagePullSecrets: $pull_values
nodeSelector: $selector
signingPolicy:
  sign_rate_limit_per_min: 0
  sign_rate_limit_per_day: 0
  rate_limits:
    - { key_id_prefix: perf-limited, per_min: 120, per_day: 100000 }
EOF

echo "==> Chart"
# shellcheck disable=SC2046 # image_args prints flags meant to be split
helm install "$RELEASE" "$CHART" -n "$ns" -f "$work/values.yaml" ${extra_values[@]+"${extra_values[@]}"} $(image_args "$cosigner_image")
# The chart keeps its volumes on uninstall: label them, so `uninstall` deletes these and no others.
for i in 1 2 3; do label pvc "data-$RELEASE-n$i"; done
wait_cosigners
k get pods -o wide
echo "==> Installed in namespace $ns"
