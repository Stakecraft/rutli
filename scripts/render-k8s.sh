#!/usr/bin/env bash
# Regenerate deploy/k8s/cosigner.yaml from the Helm chart, so the kustomize manifests and the chart
# can never drift: deploy/k8s is the chart rendered with deploy/k8s/values.yaml (topology=perNode).
#
#   scripts/render-k8s.sh           rewrite deploy/k8s/cosigner.yaml
#   scripts/render-k8s.sh --check   exit 1 if it is out of date (CI)
#
# Requires helm 3.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$REPO/deploy/k8s/cosigner.yaml"

render() {
  cat <<'HDR'
# Copyright 2026 StakeCraft
# SPDX-License-Identifier: Apache-2.0
#
# GENERATED by scripts/render-k8s.sh from deploy/helm/rutli-cosigner with deploy/k8s/values.yaml.
# Do not edit by hand: change the chart or the values and re-run the script (CI checks this file is
# current). topology=perNode: one StatefulSet + one Service per node, each pod spec referencing only
# its own seal bundle and TLS Secret. See deploy/k8s/README.md.
HDR
  helm template rutli "$REPO/deploy/helm/rutli-cosigner" --namespace rutli \
    -f "$REPO/deploy/k8s/values.yaml" | sed -e 's/[[:space:]]*$//'
}

if [ "${1:-}" = "--check" ]; then
  if ! diff -u "$OUT" <(render) >/dev/null; then
    echo "deploy/k8s/cosigner.yaml is out of date with the chart — run scripts/render-k8s.sh" >&2
    diff -u "$OUT" <(render) | head -40 >&2 || true
    exit 1
  fi
  echo "deploy/k8s/cosigner.yaml is current"
else
  render >"$OUT"
  echo "wrote $OUT"
fi
