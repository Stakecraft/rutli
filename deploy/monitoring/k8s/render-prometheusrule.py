"""Wrap deploy/monitoring/prometheus-rules.yml into a PrometheusRule CR for Prometheus Operator.

The plain rules file stays the single source of truth (docker-compose / soak stacks load it
directly); this emits the CR to stdout so it never drifts:

    deploy/monitoring/k8s/render-prometheusrule.py > deploy/monitoring/k8s/prometheusrule.yaml   (then: kubectl apply -k deploy/monitoring)
"""
import pathlib
import sys

import yaml

here = pathlib.Path(__file__).resolve().parent
rules = yaml.safe_load((here.parent / "prometheus-rules.yml").read_text())

cr = {
    "apiVersion": "monitoring.coreos.com/v1",
    "kind": "PrometheusRule",
    "metadata": {
        "name": "rutli-cosigner",
        "namespace": "rutli",
        "labels": {
            # kube-prometheus-stack's default ruleSelector
            "release": "prometheus",
            "app.kubernetes.io/name": "rutli-cosigner",
            "app.kubernetes.io/part-of": "rutli",
        },
    },
    "spec": {"groups": rules["groups"]},
}

sys.stdout.write("# GENERATED by render-prometheusrule.py from ../prometheus-rules.yml — do not edit.\n")
yaml.safe_dump(cr, sys.stdout, sort_keys=False, width=100)
